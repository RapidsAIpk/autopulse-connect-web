const INDEX = new Map();

function entry(emoji) {
  let item = INDEX.get(emoji);
  if (!item) {
    item = { names: new Set(), tags: new Set() };
    INDEX.set(emoji, item);
  }
  return item;
}

function addWords(emoji, text, bucket) {
  for (const word of String(text || "").toLowerCase().split(/\s+/).filter(Boolean)) {
    entry(emoji)[bucket].add(word);
  }
}

for (const cat of EMOJI_CATS) {
  for (const emoji of cat.items) addWords(emoji, `${cat.id} ${cat.title}`, "tags");
}
for (const [words, emojis] of KEYWORD_GROUPS) {
  for (const emoji of emojis) addWords(emoji, words, "names");
}

export function emojiKeywords(emoji) {
  const item = INDEX.get(emoji);
  return item ? [...item.names].join(" ") : "";
}

export function searchEmojis(query) {
  const terms = String(query || "").toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return [];
  const scored = [];
  for (const [emoji, item] of INDEX) {
    let score = 0;
    let miss = false;
    for (const term of terms) {
      if (item.names.has(term)) score += 5;
      else if (term.length >= 2 && [...item.names].some((word) => word.startsWith(term))) score += 3;
      else if (item.tags.has(term)) score += 1;
      else {
        miss = true;
        break;
      }
    }
    if (!miss) scored.push({ emoji, score });
  }
  scored.sort((a, b) => b.score - a.score || a.emoji.localeCompare(b.emoji));
  return scored.map((item) => item.emoji);
}
