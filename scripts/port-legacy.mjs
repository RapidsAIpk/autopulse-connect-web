// Ports the old Connect Hub frontend (autopulse-connect-hub/public — read only, never edited) into src/legacy/.
//
//  • markup/<page>.ts — each page's <body> markup, byte-for-byte (script tags removed: Next loads the code).
//  • *.js             — the screen logic, unchanged except for the transport swaps below:
//      fetch(...)              → legacyFetch(...)      (every request goes through RTK Query, same headers/handling)
//      new EventSource(events) → openLiveEvents(token) (Socket.io instead of SSE, same event names + payloads)
//      import "./x.js?v=N"     → import "./x.js"       (bundler-friendly specifiers)
//
// Re-run after any change in the old app:  node scripts/port-legacy.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const OLD = path.resolve(here, "../../autopulse-connect-hub/public");
const OUT = path.resolve(here, "../src/legacy");
mkdirSync(path.join(OUT, "markup"), { recursive: true });

const PAGES = {
  app: "app.html",
  signup: "signup.html",
  forgot: "forgot.html",
  reset: "reset.html",
  demo: "demo.html",
  contact: "contact.html",
  terms: "terms.html",
  privacy: "privacy.html",
  widgetTest: "widget/test.html",
};

for (const [name, file] of Object.entries(PAGES)) {
  const html = readFileSync(path.join(OLD, file), "utf8");
  const body = /<body[^>]*>([\s\S]*)<\/body>/i.exec(html)?.[1];
  if (body == null) throw new Error(`${file}: no <body>`);
  const markup = body.replace(/\s*<script\b[^>]*>[\s\S]*?<\/script>/gi, "").trim();
  writeFileSync(
    path.join(OUT, "markup", `${name}.ts`),
    `// GENERATED by scripts/port-legacy.mjs from autopulse-connect-hub/public/${file} — do not edit.\n` +
      `const markup = ${JSON.stringify(markup)};\nexport default markup;\n`,
  );
}

const MODULES = [
  "app.js", "emoji.js", "profile.js", "stores.js", "team.js", "stock.js", "start.js", "popups.js",
  "visitors.js", "dashcharts.js", "charts.js", "leads.js", "account.js", "site.js", "widget-test.js",
  "tz.js", "fbpage.js",
];

// Everything else in assets/ (CSS, images, help.js, theme.js, and the scripts the backend's own pages load,
// e.g. car-page.js, pages.js, fb-return.js) is served unchanged from public/assets.
// login.js is not needed: the login screen is a React component (src/components/auth/LoginView.tsx).
const PUBLIC_ASSETS = path.resolve(here, "../public/assets");
mkdirSync(PUBLIC_ASSETS, { recursive: true });
let copied = 0;
for (const file of readdirSync(path.join(OLD, "assets"))) {
  if (MODULES.includes(file) || file === "login.js") continue;
  copyFileSync(path.join(OLD, "assets", file), path.join(PUBLIC_ASSETS, file));
  copied++;
}
console.log(`static assets copied unchanged: ${copied}`);

let swaps = 0;
for (const file of MODULES) {
  let src = readFileSync(path.join(OLD, "assets", file), "utf8");
  const before = src;
  src = src.replace(/(from\s+"\.\/[\w-]+\.js)\?v=\d+"/g, '$1"');
  const fetches = (src.match(/\bfetch\(/g) || []).length;
  src = src.replace(/\bfetch\(/g, "legacyFetch(");
  const sse = (src.match(/new EventSource\(`\/api\/events\$\{query\}`\)/g) || []).length;
  src = src.replace(/new EventSource\(`\/api\/events\$\{query\}`\)/g, "openLiveEvents(state.sessionToken)");
  swaps += fetches + sse;
  const imports = [];
  if (fetches) imports.push('import { legacyFetch } from "@/lib/legacyFetch";');
  if (sse) imports.push('import { openLiveEvents } from "@/lib/liveEvents";');
  const header = `// PORTED by scripts/port-legacy.mjs from autopulse-connect-hub/public/assets/${file} — edit the port script, not this file.\n`;
  // Plain scripts (no import/export) become modules so the loader can import them; they still run top to bottom.
  if (!imports.length && !/^\s*(import|export)\b/m.test(src)) src += "\nexport {};\n";
  writeFileSync(path.join(OUT, file), header + (imports.length ? imports.join("\n") + "\n" : "") + src);
  console.log(`${file.padEnd(14)} fetch→legacyFetch: ${fetches}${sse ? `, EventSource→Socket.io: ${sse}` : ""}${src === before ? "" : ""}`);
}
console.log(`markup pages: ${Object.keys(PAGES).length}, transport swaps: ${swaps}`);
